#!/usr/bin/env python3
"""Snapshot measured experiment results into the LaTeX report (standard library only)."""

import csv
from pathlib import Path
import shutil
import sys


ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "output/experiments/recognition_grid_search"
TABLES = ROOT / "report/tables"


def read(name):
    with (SOURCE / name).open(newline="") as stream:
        return list(csv.DictReader(stream))


def escape(value):
    return str(value).replace("_", r"\_").replace("%", r"\%")


def table(name, caption, label, columns, heading, rows):
    lines = ["% Generated by experiments/writeRecognitionReport.py from saved CSVs.",
             r"\begin{table}[htbp]", r"\centering", r"\small",
             rf"\caption{{{caption}}}", rf"\label{{{label}}}",
             rf"\begin{{tabular}}{{{columns}}}", r"\toprule",
             " & ".join(heading) + r" \\", r"\midrule"]
    lines.extend(" & ".join(map(str, row)) + r" \\" for row in rows)
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", r"\FloatBarrier", ""])
    (TABLES / name).write_text("\n".join(lines))


def count(row, field):
    return f"{row[field]}/{row['matched']}"


def percent(row, field):
    return f"{100 * float(row[field]):.2f}\\%"


def main():
    TABLES.mkdir(parents=True, exist_ok=True)
    metrics = read("metrics.csv")
    configs = {r["label"]: r for r in read("finalists.csv")}
    labels = {"baseline": "Original baseline", "baseline_cloth": "Baseline + cloth filter",
              "best_type_grid": "Best K/type grid", "best_number": "Best after colour search"}
    totals = {(r["label"], r["split"]): r for r in metrics if r["image"] == "ALL"}
    rows = []
    for key, label in labels.items():
        r = totals[key, "tuning"]
        ref = totals[key, "reference"]
        rows.append([label, count(r, "typeCorrect"), percent(r, "typeAccuracy"),
                     count(r, "numberCorrect"), percent(r, "numberAccuracy"),
                     count(r, "oracleNumberCorrect"), count(ref, "numberCorrect")])
    table("recognition_search_summary.tex", "Exploratory recognition scores. Tuning uses Table1--6; "
          "the final column is full-number recognition on AllBalls, reported separately.",
          "tab:recognition-search-summary", "lrrrrrr",
          ["Configuration", "Type", "Type acc.", "Number", "Number acc.", "Oracle", "Ref. no."], rows)

    rows = []
    for k in range(2, 7):
        for cloth in (0, 1):
            group = [r for r in read("k_comparison.csv") if int(r["k"]) == k and int(r["cloth"]) == cloth]
            default = next(r for r in group if r["comparison"] == "default_thresholds")
            best = next(r for r in group if r["comparison"] == "best_type_grid")
            rows.append([k, "On" if cloth else "Off", count(default, "typeCorrect"),
                         count(default, "numberCorrect"), count(best, "typeCorrect"),
                         count(best, "numberCorrect"), best["configId"]])
    table("recognition_search_k.tex", "Effect of K and cloth filtering on Table1--6. Default columns "
          "use the original thresholds. Tuned columns select the highest-ranked stage-one configuration "
          "within each K/filter pair; colour thresholds remain fixed.",
          "tab:recognition-search-k", "rcrrrrr",
          ["K", "Cloth", "Default type", "Default no.", "Tuned type", "Tuned no.", "ID"], rows)

    baseline, best = configs["baseline"], configs["best_number"]
    names = [("k", "K"), ("cloth", "Cloth filter (0=off)"),
             ("lightMinV", "Light minimum V"), ("lightMaxS", "Light maximum S"),
             ("whiteMinPercent", r"Cue minimum light (\%)"),
             ("solidMinPercent", r"Solid minimum non-light (\%)"),
             ("bluePurple", "Blue/purple hue boundary")]
    table("recognition_search_parameters.tex", "Baseline and selected recognition parameters. "
          "Other colour parameters retain their original values.", "tab:recognition-search-parameters",
          "lrr", ["Parameter", "Baseline", "Selected"],
          [[label, baseline[key], best[key]] for key, label in names])

    by_image = {(r["label"], r["image"]): r for r in metrics if r["split"] == "tuning" and r["image"] != "ALL"}
    rows = []
    for image in sorted({key[1] for key in by_image}):
        original, chosen = by_image["baseline", image], by_image["best_number", image]
        rows.append([escape(image), original["groundTruth"], original["matched"],
                     original["typeCorrect"], chosen["typeCorrect"], original["numberCorrect"],
                     chosen["numberCorrect"]])
    table("recognition_search_images.tex", "Per-image counts before and after the recognition search. "
          "All comparisons use the same matched candidates.", "tab:recognition-search-images", "lrrrrrr",
          ["Image", "GT", "Matched", "Base type", "Best type", "Base no.", "Best no."], rows)

    counts = {(r["actual"], r["predicted"]): r["count"] for r in read("confusion.csv")
              if r["label"] == "best_number" and r["split"] == "tuning" and r["task"] == "type"}
    table("recognition_search_confusion.tex", "Selected configuration's type confusion matrix "
          "on Table1--6. Rows are ground truth and columns are predictions.",
          "tab:recognition-search-confusion", "lrrrr",
          ["Actual / predicted", "White", "Solid", "Striped", "Unknown"],
          [[actual] + [counts[actual, predicted] for predicted in ("White", "Solid", "Striped", "Unknown")]
           for actual in ("White", "Solid", "Striped")])

    padding = ROOT / "output/experiments/radius_padding"
    if padding.is_dir():
        padding_rows = []
        for path in padding.glob("*/results.csv"):
            if path.parent.name != "AllBalls":
                with path.open(newline="") as stream:
                    padding_rows.extend(csv.DictReader(stream))
        rows = []
        for mode in (0, 1):
            for pad in range(5):
                group = [r for r in padding_rows if r["trueNumber"] and
                         int(r["clothFilter"]) == mode and int(r["padding"]) == pad]
                if group:
                    rows.append([pad, "On" if mode else "Off", len(group),
                                 sum(int(r["typeCorrect"]) for r in group),
                                 sum(int(r["numberCorrect"]) for r in group)])
        table("radius_padding_results.tex", "Radius-padding experiment on matched balls in Table1--6 "
              "using the original recognition thresholds and K=2.", "tab:radius-padding-results",
              "rcrrr", ["Padding (px)", "Cloth filter", "Matched", "Correct type", "Correct number"], rows)

    example = SOURCE / "Table1/ball_3_comparison.png"
    if example.exists():
        shutil.copyfile(example, ROOT / "report/assets/recognition_search_example.png")
    print(f"Updated report tables and diagnostic figure from {SOURCE}")


if __name__ == "__main__":
    main()
